import assert from 'node:assert/strict';
import {dashIsHevcOnly,dashHevcCodecs,dashHevcDefinitelyUnsupported} from '../../src/core/dash-codecs.ts';
import {playbackTimeouts} from '../../src/core/playback-timing.ts';
const adaptation=(attrs,reps)=>`<AdaptationSet ${attrs}>${reps.map(a=>`<Representation ${a}/>`).join('')}</AdaptationSet>`;
const audio=adaptation('mimeType="audio/mp4" codecs="mp4a.40.2"',['id="audio"']);
const hevc=adaptation('contentType="video" codecs="hev1.1.6.L93.90"',['id="1"','id="2"']);
assert.equal(dashIsHevcOnly(`<MPD><Period>${hevc}${audio}</Period></MPD>`),true);
assert.equal(dashIsHevcOnly(`<MPD>${adaptation('mimeType="video/mp4"',["codecs='hvc1.1.6.L120.90'",'codecs="avc1.640028"'])}</MPD>`),false,'mixed codecs stay eligible');
assert.equal(dashIsHevcOnly(`<MPD>${adaptation('mimeType="video/mp4"',['codecs="hvc1.1.6.L120.90"','id="unknown"'])}</MPD>`),false,'unknown codec stays eligible');
assert.equal(dashIsHevcOnly(`<MPD>${hevc}<AdaptationSet contentType="video"/></MPD>`),false,'unknown representation layout stays eligible');
assert.equal(dashIsHevcOnly(`<MPD>${hevc}<AdaptationSet><Representation codecs="avc1.4d401f"/></AdaptationSet></MPD>`),false,'untyped set could be an alternative video');
assert.equal(dashIsHevcOnly(`<MPD>${audio}</MPD>`),false);
assert.equal(dashIsHevcOnly('<MPD/>'),false);
const exact=`<MPD><Period>${hevc}${audio}</Period></MPD>`;
assert.deepEqual(dashHevcCodecs(exact),['hev1.1.6.L93.90']);
assert.equal(dashHevcDefinitelyUnsupported(exact,mime=>mime.includes('hev1.1.6.L93.90')),false,'the advertised profile must be tested, not a generic profile');
assert.equal(dashHevcDefinitelyUnsupported(exact,()=>false),true);
assert.equal(dashHevcDefinitelyUnsupported(exact,()=>{throw Error('probe failure')}),false,'unknown capability remains eligible');
assert.equal(dashHevcDefinitelyUnsupported('<MPD/>',()=>false),false);
assert.deepEqual(playbackTimeouts(['slowManifest']),{manifest:12000,level:12000,fragment:15000,startup:15000});
assert.deepEqual(playbackTimeouts(['hevcFirst']),{manifest:12000,level:12000,fragment:15000,startup:15000});
assert.deepEqual(playbackTimeouts(['aggregator']),{manifest:5500,level:5500,fragment:7000,startup:10000});
console.log('DASH codec guards and trait-driven playback timing passed');
